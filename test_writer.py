"""
TestFileWriter for CodeShield AI.

Writes generated test suites to disk in the appropriate directory structure
for each language and framework. Handles:
- Existing test file detection (prevents overwriting)
- Import resolution
- Fixture/setup code generation
- conftest.py creation for shared fixtures
- __tests__ directory creation for JavaScript
- Maven/Gradle test directory structure for Java
- Co-located Go test files
"""

import os
import re
from pathlib import Path
from typing import Any, Dict, List, Optional, Set

from utils.logger import get_logger

from agents.test_generator import GeneratedTest, TestSuite

logger = get_logger(__name__)

# ---------------------------------------------------------------------------
# Default paths per language/framework
# ---------------------------------------------------------------------------

DEFAULT_OUTPUT_PATHS = {
    "python": {
        "pytest": "tests",
        "file_pattern": "test_{module}.py",
        "fixture_file": "conftest.py",
    },
    "javascript": {
        "jest": "__tests__",
        "file_pattern": "{module}.test.js",
        "fixture_file": "jest.setup.js",
    },
    "typescript": {
        "jest": "__tests__",
        "file_pattern": "{module}.test.ts",
        "fixture_file": "jest.setup.ts",
    },
    "java": {
        "junit5": "src/test/java",
        "file_pattern": "{package}/{class_name}Test.java",
        "fixture_file": "TestConfig.java",
    },
    "go": {
        "go_test": ".",  # Co-located with source
        "file_pattern": "{module}_test.go",
        "fixture_file": "test_helper.go",
    },
}

