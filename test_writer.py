def write_test_suites(
    suites: List[TestSuite],
    output_base: Optional[str] = None,
    overwrite: bool = False,
    create_fixtures: bool = True,
) -> Dict[str, Any]:
    """
    Convenience function to write test suites without instantiating TestFileWriter.

    Args:
        suites: List of test suites to write
        output_base: Base directory for output
        overwrite: Whether to overwrite existing files
        create_fixtures: Whether to create shared fixture files

    Returns:
        Dict with summary of write operations
    """
    writer = TestFileWriter(
        output_base=output_base,
        overwrite=overwrite,
        create_fixtures=create_fixtures,
    )
    return writer.write_all_suites(suites)
